def niveau(sc) -> int:
    """Niveau de pertinence d'une sous-catégorie (objet SousCategorie)."""
    return NIVEAUX_SC.get(sc.id, NIVEAUX_FAMILLES.get(sc.famille, 3))


def objet_ancien_admis(sc) -> bool:
    """Un objet ancien peut-il documenter cette sous-catégorie ?"""
    return sc.famille == "ANC" or niveau(sc) >= 3 or sc.id in FORMES_INTEMPORELLES
